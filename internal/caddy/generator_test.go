func TestGenerateCaddyfileProviderPresets(t *testing.T) {
	tests := []struct {
		name       string
		config     TLSConfig
		directive  string
		notPresent string
	}{
		{"cloudflare", TLSConfig{DNSProvider: "cloudflare", DNSProviderModule: "cloudflare"}, "dns cloudflare {env.CLOUDFLARE_API_TOKEN}", ""},
		{"digitalocean", TLSConfig{DNSProvider: "digitalocean", DNSProviderModule: "digitalocean"}, "dns digitalocean {env.DO_AUTH_TOKEN}", ""},
		{"route53", TLSConfig{DNSProvider: "route53", DNSProviderModule: "route53", DNSTokenEnvVar: "INCORRECT_TOKEN"}, "dns route53", "dns route53 {env."},
		{"custom single-token provider", TLSConfig{DNSProvider: "custom", DNSProviderModule: "acmedns", DNSTokenEnvVar: "ACMEDNS_TOKEN"}, "dns acmedns {env.ACMEDNS_TOKEN}", ""},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			output, err := GenerateCaddyfile([]RouteInfo{{Domain: "app.example.com", Port: 3000}}, tt.config, "example.com")
			if err != nil {
				t.Fatalf("GenerateCaddyfile() error = %v", err)
			}
			if !strings.Contains(output, tt.directive) {
				t.Fatalf("output does not contain %q:\n%s", tt.directive, output)
			}
			if tt.notPresent != "" && strings.Contains(output, tt.notPresent) {
				t.Fatalf("output unexpectedly contains %q:\n%s", tt.notPresent, output)
			}
		})
	}
}
